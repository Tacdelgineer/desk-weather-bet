#!/usr/bin/env python3
"""Build chapters/NN_name.html (the page) from the voice take + chapters/NN_scenes.js (the shots).

  python3 tools/mkpage.py NN [tail_seconds]

Writes chapters/NN.chunks.txt (one sentence per line), chapters/NN.words.js (word timings), and the page with
CAPS from tacdel-shorts tools/timing.py caps, DUR = voice end + tail, and an empty WARP, so
`timing.py warp voice/NN.words.json chapters/NN.chunks.txt chapters/NN_name.html --write` re-times it to a new take.
Loads every chapters/tx/*.js (real logs for CRT replays, if the project has any) before common.js.
"""
import json, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kit
ROOT = kit.ROOT
TIMING = os.path.join(kit.SHORTS_TOOLS, 'timing.py')
CH = kit.chapters(); NAMES = {k: v[0] for k, v in CH.items()}; TITLES = {k: v[1] for k, v in CH.items()}
VIDEO_TITLE = kit.video()['title']
n = sys.argv[1]; tail = float(sys.argv[2]) if len(sys.argv) > 2 else 1.2
text = open(f'{ROOT}/voice/text/{n}.txt').read()
spoken = re.sub(r'<[^>]+>', ' ', text)
sents = [s.strip() for s in re.split(r'(?<=[.?!])\s+|(?<=[.?!]["”])\s+', ' '.join(spoken.split())) if s.strip()]   # also after a closing quote
open(f'{ROOT}/chapters/{n}.chunks.txt', 'w').write('\n'.join(sents) + '\n')
words = json.load(open(f'{ROOT}/voice/{n}.words.json'))['words']
open(f'{ROOT}/chapters/{n}.words.js', 'w').write('window.WORDS = ' + json.dumps(words, separators=(',', ':')) + ';\n')
caps = subprocess.run([sys.executable, TIMING, 'caps', f'{ROOT}/voice/{n}.words.json', f'{ROOT}/chapters/{n}.chunks.txt'], capture_output=True, text=True, check=True).stdout
caps = caps.split('\n// voice ends')[0].strip()
dur = round(words[-1]['end'] + tail, 1)
txdir = f'{ROOT}/chapters/tx'
TXS = '\n'.join(f'<script src="tx/{f}"></script>' for f in sorted(os.listdir(txdir)) if f.endswith('.js')) if os.path.isdir(txdir) else ''
page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{n} {TITLES[n]}</title>
<!--
  {VIDEO_TITLE} · chapter {n} · {TITLES[n]} · 1920x1080 · 30 fps
  Generated by tools/mkpage.py (shots live in {n}_scenes.js; looks in ../styles/). Voice: ../voice/{n}.wav (mismatch lines muted).
  KEYS  Space play/pause · R restart · Left/Right shot · H hide controls   URL  ?clean · ?t=12 · ?caps
-->
<link rel="stylesheet" href="../styles/fonts.css">
</head>
<body>
<canvas id="c" width="1920" height="1080"></canvas>
<div id="hud"><div id="bar"><div id="fill"></div></div><div id="row"><span id="info"></span><span>Space · R · ← → · H</span></div></div>
<script>
const TITLE = {json.dumps(n + ' · ' + TITLES[n], ensure_ascii=False)}, VOICE = '../voice/{n}.wav';
{caps}
const DUR = {dur};
// re-timing to a new voice take (timing.py warp): [[time in the new take, time these shots were written for], ...]
const WARP = [];
</script>
<script src="{n}.words.js"></script>
<script src="data.js"></script>
<script src="../styles/core.js"></script>
<script src="../styles/riso.js"></script>
<script src="../styles/papercut.js"></script>
<script src="../styles/crt.js"></script>
{TXS}
<script src="common.js"></script>
<script src="{n}_scenes.js"></script>
<script>start();</script>
</body>
</html>
'''
out = f'{ROOT}/chapters/{n}_{NAMES[n]}.html'; open(out, 'w').write(page)
print(out, 'DUR', dur, 'chunks', len(sents))
